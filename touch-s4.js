function paint(inp){
  var n = parseInt(inp.value,10) || 0;
  inp.classList.toggle("mx4-fill", n > 0);
  var row = inp.closest ? inp.closest(".mx4-arow") : null;
  if (row) row.classList.toggle("mx4-has", n > 0);
}
function readAlloc(){
  var nums = mbody.querySelectorAll(".mx4-num"), out = [], sum = 0;
  for (var i=0;i<nums.length;i++){
    var n = parseInt(nums[i].value,10);
    if (!(n > 0)) n = 0;
    out.push(n); sum += n;
  }
  return { counts: out, sum: sum };
}
function total(){
  var el = document.getElementById("mx4-sum");
  if (el) el.textContent = readAlloc().sum;
}

function submitEntry(){
  var btn = document.getElementById("mx4-send");
  var name = document.getElementById("mx4-name").value.trim();
  var phone = document.getElementById("mx4-phone").value.trim();
  var agree = document.getElementById("mx4-agree").checked;
  var a = readAlloc();

  ["mx4-mName","mx4-mPhone","mx4-mAlloc","mx4-mAgree","mx4-err"].forEach(function(id){
    var el = document.getElementById(id); if (el) el.classList.remove("mx4-show");
  });

  var bad = null;
  if (name.length < 2){
    document.getElementById("mx4-mName").classList.add("mx4-show");
    document.getElementById("mx4-name").classList.add("mx4-bad");
    bad = bad || "mx4-name";
  } else document.getElementById("mx4-name").classList.remove("mx4-bad");

  if (phone.replace(/[^0-9]/g,"").length < 10){
    document.getElementById("mx4-mPhone").classList.add("mx4-show");
    document.getElementById("mx4-phone").classList.add("mx4-bad");
    bad = bad || "mx4-phone";
  } else document.getElementById("mx4-phone").classList.remove("mx4-bad");

  if (a.sum < 1){
    document.getElementById("mx4-mAlloc").classList.add("mx4-show");
    bad = bad || "mx4-sum";
  }
  if (!agree){
    document.getElementById("mx4-mAgree").classList.add("mx4-show");
    bad = bad || "mx4-agree";
  }
  if (bad){
    document.getElementById(bad).scrollIntoView({behavior:"smooth",block:"center"});
    return;
  }

  if (!CONFIG.formUrl && !CONFIG.scriptUrl){
    var e0 = document.getElementById("mx4-err");
    e0.textContent = "응모 접수 주소가 설정되지 않았습니다. 생성기에서 접수 주소를 입력해주세요.";
    e0.classList.add("mx4-show"); return;
  }

  var names = [], detail = [];
  for (var i=0;i<CONFIG.models.length;i++){
    names.push(CONFIG.models[i].name);
    if (a.counts[i] > 0) detail.push(CONFIG.models[i].name + ":" + a.counts[i]);
  }
  var detailText = detail.join(" / ");

  btn.disabled = true; btn.textContent = "접수 중";

  function failed(){
    var eb = document.getElementById("mx4-err");
    eb.textContent = "접수에 실패했습니다. 잠시 후 다시 시도해주세요. 계속 같은 문제가 생기면 고객센터로 문의해주세요.";
    eb.classList.add("mx4-show");
    btn.disabled = false; btn.textContent = "응모 접수하기";
  }

  /* ── 구글 폼 방식 ── */
  if (CONFIG.formUrl){
    var fd = new URLSearchParams();
    if (CONFIG.entryName)   fd.append(CONFIG.entryName, name);
    if (CONFIG.entryPhone)  fd.append(CONFIG.entryPhone, phone);
    if (CONFIG.entryTotal)  fd.append(CONFIG.entryTotal, String(a.sum));
    if (CONFIG.entryDetail) fd.append(CONFIG.entryDetail, detailText);

    // 구글 폼은 응답을 돌려주지 않아 성공 여부를 읽을 수 없습니다.
    // 전송이 끝나면 접수된 것으로 처리합니다.
    fetch(CONFIG.formUrl, { method:"POST", mode:"no-cors", body:fd })
      .then(function(){ doneStep(name, a, detail); })
      .catch(function(){ failed(); });
    return;
  }

  /* ── Apps Script 방식 ── */
  fetch(CONFIG.scriptUrl, { method:"POST", body:new URLSearchParams({
    name: name, phone: phone,
    total: String(a.sum),
    names: names.join("|"),
    counts: a.counts.join("|"),
    detail: detailText
  })})
  .then(function(r){ return r.json(); })
  .then(function(res){
    if (res && res.result === "success") doneStep(name, a, detail);
    else throw new Error("fail");
  })
  .catch(failed);
}

function doneStep(name, a, detail){
  var lines = [];
  for (var i=0;i<CONFIG.models.length;i++){
    if (a.counts[i] > 0){
      lines.push('<div class="mx4-tr"><span>'+esc(CONFIG.models[i].name)
        + ' &#183; '+esc(CONFIG.models[i].item)+'</span><b>'+a.counts[i]+'장</b></div>');
    }
  }
  mbody.innerHTML = '<div class="mx4-done"><div class="mx4-ico">'+SVG.lipFill+'</div>'
    + '<h3>응모가 접수됐습니다</h3>'
    + '<p>마감 전까지는 다시 제출해서 배분을 바꾸실 수 있습니다. 당첨자는 발표일에 개별 연락드립니다.</p>'
    + '<div class="mx4-tix" style="margin-top:26px;text-align:left">'
    +   '<div class="mx4-tt">'+esc(name)+' 님의 응모 내역</div>' + lines.join("")
    +   '<div class="mx4-tr" style="border-top:1px solid #F1EBEF;margin-top:8px;padding-top:9px">'
    +     '<span>합계</span><b>'+a.sum+'장</b></div>'
    + '</div>'
    + '<div><button type="button" class="mx4-doneclose" id="mx4-fin">닫기</button></div></div>';
  mbody.scrollTop = 0;
  document.getElementById("mx4-fin").addEventListener("click", closeModal);

  var cards = document.querySelectorAll("#mx4-event .mx4-card");
  for (var j=0;j<cards.length;j++) cards[j].classList.toggle("mx4-on", a.counts[j] > 0);
}
